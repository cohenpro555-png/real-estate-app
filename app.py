        {"כתובת": "רחוב העצמאות 12, חיפה", "סוג": "דירת מגורים", "סטטוס": "מושכרת", "שכירות": "₪ 4,500", "תשואה": "4.2%"},
        {"כתובת": "שדרות הנשיא 45, חדרה", "סוג": "דירת מגורים", "סטטוס": "בשיפוץ", "שכירות": "₪ 0", "תשואה": "0%"},
